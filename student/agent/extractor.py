"""Extraction of Python code blocks from LLM answers."""

import re

# A closed block whose label is not exactly "python" but is still Python:
# no label, py, py3, python3, or any case of "python" (```Python)
OTHER_LABEL_PATTERN = r"```(?:[Pp][Yy](?:thon|THON)?3?)?[ \t]*\n(.*?)```"


def extract_code(answer_content: str) -> tuple[str, str | None]:
    """Extract the Python code written by the LLM in its answer.

    Every block delimited by ```python and ``` is extracted. When there are
    several blocks, they are joined in order, separated by a newline.

    Malformed blocks are executed anyway, with a warning for the LLM: a
    block with another Python label (```py, ```Python, ``` alone) or a
    ```python block that is never closed.

    Args:
        answer_content: The raw text generated by the LLM.

    Returns:
        A (code, warning) tuple: the code of all the blocks, stripped and
        joined into one string, and a message for the LLM if its code block
        was malformed but executed anyway (None if the format was correct).

    Raises:
        ValueError: If the answer contains no ```python block.
    """
    start = "```python"
    end = "```"

    # The label must end the line, so ```python3 is not read as ```python
    pattern = rf"{start}[ \t]*\n(.*?){end}"
    # re.DOTALL for the pattern to be multi-lines
    matches: list[str] = re.findall(pattern, answer_content, re.DOTALL)

    if not matches:
        # Closed blocks with another label (```py, ```Python, ``` alone...)
        other_blocks = re.findall(OTHER_LABEL_PATTERN, answer_content, re.DOTALL)
        other_code = [code.strip() for code in other_blocks if code.strip()]
        if other_code:
            warning = (
                "Warning: your code block was not tagged ```python, it was "
                "executed as Python anyway. Always start your code block "
                "with ```python."
            )
            return "\n".join(other_code), warning

        # ```python is there but never closed: run everything after it
        unclosed = re.search(rf"{start}[ \t]*\n(.*)", answer_content, re.DOTALL)
        if unclosed:
            code = unclosed.group(1).strip()
            if code:
                warning = (
                    "Warning: your code block had no closing ```. Everything "
                    "after ```python was executed. Always close your code "
                    "block with ```."
                )
                return code, warning

        raise ValueError(
            "No code provided. You should provide python code to answer query, with ```python tag."
        )

    result = []
    for match in matches:
        code_block = match.strip()
        result.append(code_block)

    return "\n".join(result), None
