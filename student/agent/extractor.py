"""Extraction of Python code blocks from LLM answers."""

import re


def extract_code(answer_content: str) -> str:
    """Extract the Python code written by the LLM in its answer.

    Every block delimited by ```python and ``` is extracted. When there are
    several blocks, they are joined in order, separated by a newline.

    Args:
        answer_content: The raw text generated by the LLM.

    Returns:
        The code of all the blocks, stripped and joined into one string.

    Raises:
        ValueError: If the answer contains no ```python block.
    """
    start = "```python"
    end = "```"

    pattern = rf"{start}(.*?){end}"
    # re.DOTALL for the pattern to be multi-lines
    matches: list[str] = re.findall(pattern, answer_content, re.DOTALL)

    if not matches:
        raise ValueError(
            "No code provided. You should provide python code to answer query, with ```python tag."
        )

    result = []
    for match in matches:
        code_block = match.strip()
        result.append(code_block)

    return "\n".join(result)
