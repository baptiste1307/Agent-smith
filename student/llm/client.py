import re
import time
from dataclasses import dataclass
from typing import Any

import httpx

from llm.rotator import KeyRotator


@dataclass
class LLMResponse:
    """Data structure for the LLM response."""

    content: str  # text generated by AI
    input_tokens: int  # numbers of input tokens
    output_tokens: int  # number of output tokens generated
    request_time_ms: float
    retries: int
    model_name: str
    api_url: str  # url of api used


@dataclass
class LLMClient:
    provider_url: str
    model_name: str
    rotator: KeyRotator  # provides the currently used API key
    timeout_seconds: float = 60.0  # Max waiting time for HTTP request
    max_retries: int = (
        6  # bounded retries so rate limits don't exceed task timeout
    )

    def __post_init__(self) -> None:
        if not self.provider_url.endswith("/chat/completions"):
            self.endpoint = f"{self.provider_url.rstrip('/')}/chat/completions"
        else:
            self.endpoint = self.provider_url

    def prepare_message(
        self,
        messages: list[dict[str, str]],
        stop: list[str] | None = None,
        temperature: float = 0.0,
    ) -> tuple[dict[str, str], dict[str, Any]]:
        """Prepare HTTP headers and payload with current API key."""
        headers = {
            "Authorization": f"Bearer {self.rotator.get_current_key()}",
            "Content-Type": "application/json",
        }
        payload: dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": 1536,
        }
        if stop:
            payload["stop"] = stop

        return headers, payload

    def send_message(
        self,
        headers: dict[str, str],
        payload: dict[str, Any],
    ) -> httpx.Response:
        """Send HTTP POST request to endpoint."""
        return httpx.post(
            self.endpoint,
            json=payload,
            headers=headers,
            timeout=self.timeout_seconds,
        )

    @staticmethod
    def _parse_retry_delay(
        response: httpx.Response, attempt: int = 0
    ) -> float:
        """Extract the recommended wait time from a rate-limit response.

        Checks (in order):
        1. Retry-After header (seconds, capped at 45s)
        2. "try again in Xs" pattern in the response body (capped at 45s)
        3. Bounded exponential backoff fallback
           (5s, 10s, 15s, ... capped at 30s)
        """
        # 1. Retry-After header
        retry_after = response.headers.get("retry-after")
        if retry_after:
            try:
                return min(max(float(retry_after), 1.0), 45.0)
            except ValueError:
                pass

        # 2. Parse delay from error message body
        try:
            body = response.text
            m = re.search(
                r"(?:try again in|retry after)\s+(\d+(?:\.\d+)?)\s*s",
                body,
                re.IGNORECASE,
            )
            if m:
                return min(max(float(m.group(1)), 1.0), 45.0)
        except Exception:
            pass

        # 3. Bounded backoff fallback
        return min(5.0 * (attempt + 1), 30.0)

    def generate(
        self,
        messages: list[dict[str, str]],
        stop: list[str] | None = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        """Generate response from LLM with automatic retry and key rotation."""
        last_error = "no attempt made"  # kept to explain the final failure

        for attempt in range(self.max_retries + 1):
            headers, payload = self.prepare_message(
                messages, stop, temperature
            )

            try:
                start_time = time.perf_counter()
                response = self.send_message(headers, payload)
                elapsed_ms = (time.perf_counter() - start_time) * 1000

                # Success case 200 OK
                if response.status_code == 200:
                    data = response.json()
                    choice = data["choices"][0]
                    message = choice.get("message", {})
                    raw_content = message.get("content")
                    if raw_content is None:
                        tool_calls = message.get("tool_calls", [])
                        if tool_calls:
                            parts = []
                            for tc in tool_calls:
                                fn = tc.get("function", {})
                                name = fn.get("name", "")
                                args = fn.get("arguments", "{}")
                                parts.append(
                                    "<tool_call>\n"
                                    '{'
                                    f'"name": "{name}", "arguments": {args}'
                                    '}'
                                    "\n</tool_call>"
                                )
                            raw_content = "\n".join(parts)
                        else:
                            raw_content = ""

                    usage = data.get("usage") or {}
                    return LLMResponse(
                        content=raw_content,
                        input_tokens=usage.get("prompt_tokens", 0),
                        output_tokens=usage.get("completion_tokens", 0),
                        request_time_ms=elapsed_ms,
                        retries=attempt,
                        model_name=self.model_name,
                        api_url=self.provider_url,
                    )

                last_error = (
                    f"HTTP {response.status_code}: {response.text[:500]}"
                )

                # Some providers (e.g. Groq on gpt-oss) return HTTP 400 with
                # `code: "tool_use_failed"` and raw tool call
                # inside `failed_generation`.
                # Recover it as a <tool_call> block so the extraction layer can
                # convert it.
                if response.status_code == 400:
                    try:
                        err_obj = response.json().get("error", {})
                        failed_gen = err_obj.get("failed_generation")
                        if (
                            err_obj.get("code") == "tool_use_failed"
                            and failed_gen
                        ):
                            return LLMResponse(
                                content=(
                                    f"<tool_call>\n{failed_gen}\n"
                                    "</tool_call>"
                                ),
                                input_tokens=0,
                                output_tokens=0,
                                request_time_ms=elapsed_ms,
                                retries=attempt,
                                model_name=self.model_name,
                                api_url=self.provider_url,
                            )
                    except Exception:
                        pass

                # Request errors (bad request, invalid key, forbidden, unknown
                # model): retrying would give the same result, so stop now
                if response.status_code in (400, 401, 403, 404):
                    raise RuntimeError(f"LLM request rejected: {last_error}")

                # Case quota / rate limit (429, 402): rotate key and retry
                if response.status_code in (429, 402):
                    num_keys = (
                        len(self.rotator.keys) if self.rotator.keys else 1
                    )
                    self.rotator.rotate_key()

                    # If multiple keys are available and we haven't looped
                    # through all of them yet,
                    # retry immediately on the next fresh key
                    if num_keys > 1 and (attempt + 1) % num_keys != 0:
                        print(
                            "[LLM] Rate limited "
                            f"(HTTP {response.status_code}). "
                            "Rotated to next key "
                            f"({self.rotator.current_index + 1}/{num_keys}), "
                            "retrying in 0.5s..."
                        )
                        time.sleep(0.5)
                        continue

                    # All keys exhausted or single key: wait the cooldown
                    # specified by provider
                    wait_secs = self._parse_retry_delay(
                        response, attempt=attempt
                    )
                    print(
                        "[LLM] Rate limited on all keys "
                        f"(HTTP {response.status_code}). "
                        f"Waiting {wait_secs:.0f}s before retry "
                        f"{attempt + 1}/{self.max_retries}..."
                    )
                    time.sleep(wait_secs)
                    continue

                # Server error (ex: 500)
                time.sleep(1)

            except (httpx.TimeoutException, httpx.NetworkError) as e:
                last_error = f"{type(e).__name__}: {e}"
                time.sleep(1)

        raise RuntimeError(
            f"Failed after {self.max_retries + 1} attempts. "
            f"Last error: {last_error}"
        )
