import json
import re
import time
from dataclasses import dataclass
from typing import Any

import httpx

from llm.rotator import KeyRotator


@dataclass
class LLMResponse:
    """Data structure for the LLM response."""

    content: str  # text generated by AI
    input_tokens: int  # numbers of input tokens
    output_tokens: int  # number of output tokens generated
    request_time_ms: float
    retries: int
    model_name: str
    api_url: str  # url of api used
    # True when the provider gave no usage and the counts are estimates
    estimated_tokens: bool = False


DEFAULT_MAX_TOKENS = 1536

# Pessimistic characters-per-token ratio, used when the provider reports
# no token usage: over-counting keeps the benchmark limits safe
ESTIMATED_CHARS_PER_TOKEN = 3.0


def estimate_tokens(text: str) -> int:
    """Estimate (rounding up) the number of tokens of a text."""
    return max(1, int(len(text) / ESTIMATED_CHARS_PER_TOKEN) + 1)


def _usage_or_estimate(
    usage: dict[str, Any],
    messages: list[dict[str, str]],
    content: str,
) -> tuple[int, int, bool]:
    """Return (input_tokens, output_tokens, estimated).

    The provider's counts are used when present. Otherwise (no `usage`
    block, or an error answer such as Groq's tool_use_failed, which still
    consumed tokens) they are estimated from the request and the answer:
    recording 0 would hide real consumption from the limits.
    """
    input_tokens = usage.get("prompt_tokens") or 0
    output_tokens = usage.get("completion_tokens") or 0
    if input_tokens > 0:
        return input_tokens, output_tokens, False
    prompt = "\n".join(m.get("content", "") for m in messages)
    return estimate_tokens(prompt), estimate_tokens(content), True


# HTTP statuses for which retrying the same request cannot succeed:
# bad request, invalid key, forbidden, unknown model, request too large
# (e.g. Groq 413 when one request exceeds the tokens-per-minute limit),
# unprocessable request
NON_RETRYABLE_STATUSES = (400, 401, 403, 404, 413, 422)

# Below this many seconds before the deadline, no new request is sent
MIN_REQUEST_SECONDS = 3.0


@dataclass
class LLMClient:
    provider_url: str
    model_name: str
    rotator: KeyRotator  # provides the currently used API key
    timeout_seconds: float = 60.0  # Max waiting time for HTTP request
    max_retries: int = (
        6  # bounded retries so rate limits don't exceed task timeout
    )

    def __post_init__(self) -> None:
        if not self.provider_url.endswith("/chat/completions"):
            self.endpoint = f"{self.provider_url.rstrip('/')}/chat/completions"
        else:
            self.endpoint = self.provider_url

    def prepare_message(
        self,
        messages: list[dict[str, str]],
        stop: list[str] | None = None,
        temperature: float = 0.0,
        max_tokens: int = DEFAULT_MAX_TOKENS,
    ) -> tuple[dict[str, str], dict[str, Any]]:
        """Prepare HTTP headers and payload with current API key."""
        headers = {
            "Authorization": f"Bearer {self.rotator.get_current_key()}",
            "Content-Type": "application/json",
        }
        payload: dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }
        if stop:
            payload["stop"] = stop

        return headers, payload

    def send_message(
        self,
        headers: dict[str, str],
        payload: dict[str, Any],
        timeout: float | None = None,
    ) -> httpx.Response:
        """Send HTTP POST request to endpoint.

        Args:
            headers: HTTP headers (with the API key).
            payload: JSON body of the request.
            timeout: HTTP timeout in seconds; defaults to timeout_seconds.
        """
        return httpx.post(
            self.endpoint,
            json=payload,
            headers=headers,
            timeout=self.timeout_seconds if timeout is None else timeout,
        )

    def _time_budget(self, deadline: float | None, last_error: str) -> float:
        """Return the HTTP timeout allowed by the deadline.

        Args:
            deadline: time.perf_counter() value not to exceed, or None.
            last_error: Error of the previous attempt, for the message.

        Raises:
            RuntimeError: If too little time is left for a request.
        """
        if deadline is None:
            return self.timeout_seconds
        left = deadline - time.perf_counter()
        if left < MIN_REQUEST_SECONDS:
            raise RuntimeError(
                "Time budget exhausted before the LLM answered "
                f"({max(left, 0):.1f}s left). Last error: {last_error}"
            )
        return min(self.timeout_seconds, left)

    @staticmethod
    def _sleep(seconds: float, deadline: float | None) -> None:
        """Wait before a retry, without going past the deadline."""
        if deadline is not None:
            seconds = min(seconds, max(0.0, deadline - time.perf_counter()))
        time.sleep(seconds)

    @staticmethod
    def _parse_retry_delay(
        response: httpx.Response, attempt: int = 0
    ) -> float:
        """Extract the recommended wait time from a rate-limit response.

        Checks (in order):
        1. Retry-After header (seconds, capped at 45s)
        2. "try again in Xs" pattern in the response body (capped at 45s)
        3. Bounded exponential backoff fallback
           (5s, 10s, 15s, ... capped at 30s)
        """
        # 1. Retry-After header
        retry_after = response.headers.get("retry-after")
        if retry_after:
            try:
                return min(max(float(retry_after), 1.0), 45.0)
            except ValueError:
                pass

        # 2. Parse delay from error message body
        try:
            body = response.text
            m = re.search(
                r"(?:try again in|retry after)\s+(\d+(?:\.\d+)?)\s*s",
                body,
                re.IGNORECASE,
            )
            if m:
                return min(max(float(m.group(1)), 1.0), 45.0)
        except Exception:
            pass

        # 3. Bounded backoff fallback
        return min(5.0 * (attempt + 1), 30.0)

    def generate(
        self,
        messages: list[dict[str, str]],
        stop: list[str] | None = None,
        temperature: float = 0.0,
        max_tokens: int = DEFAULT_MAX_TOKENS,
        deadline: float | None = None,
    ) -> LLMResponse:
        """Generate response from LLM with automatic retry and key rotation.

        Args:
            messages: The conversation sent to the model.
            stop: Optional stop sequences.
            temperature: Sampling temperature.
            max_tokens: Maximum number of tokens the model may generate.
            deadline: Optional time.perf_counter() value: requests and
                retry waits are shortened so that generate() never runs
                past it.

        Raises:
            RuntimeError: If the request is rejected, if every retry
                failed, or if the deadline leaves no time for a request.
        """
        last_error = "no attempt made"  # kept to explain the final failure

        for attempt in range(self.max_retries + 1):
            http_timeout = self._time_budget(deadline, last_error)
            headers, payload = self.prepare_message(
                messages, stop, temperature, max_tokens
            )

            try:
                start_time = time.perf_counter()
                response = self.send_message(headers, payload, http_timeout)
                elapsed_ms = (time.perf_counter() - start_time) * 1000

                # Success case 200 OK
                if response.status_code == 200:
                    data = response.json()
                    choice = data["choices"][0]
                    message = choice.get("message", {})
                    raw_content = message.get("content")
                    if raw_content is None:
                        tool_calls = message.get("tool_calls", [])
                        if tool_calls:
                            parts = []
                            for tc in tool_calls:
                                fn = tc.get("function", {})
                                name = fn.get("name", "")
                                args = fn.get("arguments", "{}")
                                # Some providers send arguments as a JSON
                                # string, others as an object: json.dumps
                                # always produces valid JSON for the
                                # <tool_call> extractor.
                                call = json.dumps(
                                    {"name": name, "arguments": args}
                                )
                                parts.append(
                                    f"<tool_call>\n{call}\n</tool_call>"
                                )
                            raw_content = "\n".join(parts)
                        else:
                            raw_content = ""

                    in_tok, out_tok, estimated = _usage_or_estimate(
                        data.get("usage") or {}, messages, raw_content
                    )
                    return LLMResponse(
                        content=raw_content,
                        input_tokens=in_tok,
                        output_tokens=out_tok,
                        request_time_ms=elapsed_ms,
                        retries=attempt,
                        model_name=self.model_name,
                        api_url=self.provider_url,
                        estimated_tokens=estimated,
                    )

                last_error = (
                    f"HTTP {response.status_code}: {response.text[:500]}"
                )

                # Some providers (e.g. Groq on gpt-oss) return HTTP 400 with
                # `code: "tool_use_failed"` and raw tool call
                # inside `failed_generation`.
                # Recover it as a <tool_call> block so the extraction layer can
                # convert it.
                if response.status_code == 400:
                    try:
                        err_obj = response.json().get("error", {})
                        failed_gen = err_obj.get("failed_generation")
                        if (
                            err_obj.get("code") == "tool_use_failed"
                            and failed_gen
                        ):
                            content = (
                                f"<tool_call>\n{failed_gen}\n</tool_call>"
                            )
                            # The error carries no usage, but the
                            # generation consumed tokens: estimate them
                            in_tok, out_tok, estimated = _usage_or_estimate(
                                {}, messages, failed_gen
                            )
                            return LLMResponse(
                                content=content,
                                input_tokens=in_tok,
                                output_tokens=out_tok,
                                request_time_ms=elapsed_ms,
                                retries=attempt,
                                model_name=self.model_name,
                                api_url=self.provider_url,
                                estimated_tokens=estimated,
                            )
                    except Exception:
                        pass

                # Request errors: retrying would give the same result, so
                # stop now
                if response.status_code in NON_RETRYABLE_STATUSES:
                    raise RuntimeError(f"LLM request rejected: {last_error}")

                # Case quota / rate limit (429, 402): rotate key and retry
                if response.status_code in (429, 402):
                    num_keys = (
                        len(self.rotator.keys) if self.rotator.keys else 1
                    )
                    self.rotator.rotate_key()

                    # If multiple keys are available and we haven't looped
                    # through all of them yet,
                    # retry immediately on the next fresh key
                    if num_keys > 1 and (attempt + 1) % num_keys != 0:
                        print(
                            "[LLM] Rate limited "
                            f"(HTTP {response.status_code}). "
                            "Rotated to next key "
                            f"({self.rotator.current_index + 1}/{num_keys}), "
                            "retrying in 0.5s..."
                        )
                        self._sleep(0.5, deadline)
                        continue

                    # All keys exhausted or single key: wait the cooldown
                    # specified by provider
                    wait_secs = self._parse_retry_delay(
                        response, attempt=attempt
                    )
                    print(
                        "[LLM] Rate limited on all keys "
                        f"(HTTP {response.status_code}). "
                        f"Waiting {wait_secs:.0f}s before retry "
                        f"{attempt + 1}/{self.max_retries}..."
                    )
                    self._sleep(wait_secs, deadline)
                    continue

                # Server error (ex: 500)
                self._sleep(1, deadline)

            except (httpx.TimeoutException, httpx.NetworkError) as e:
                last_error = f"{type(e).__name__}: {e}"
                self._sleep(1, deadline)

        raise RuntimeError(
            f"Failed after {self.max_retries + 1} attempts. "
            f"Last error: {last_error}"
        )
